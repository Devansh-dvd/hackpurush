#!/usr/bin/env python3
"""
gen_key.py — IRONCLAD key generator
====================================
Generates a cryptographically random 16-byte AES-128 pre-shared key
and writes it directly into firmware/secrets.h (overwriting any old file).

Usage:
    python scripts/gen_key.py

Both the controller ESP32 (ironclad_tx) and the rover ESP32 (ironclad_rx)
must be flashed with identical secrets.h files.

KEEP secrets.h OUT OF GIT — it is already in .gitignore.
"""

import secrets
import os
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_FILE = ROOT / "firmware" / "secrets.h"
EXAMPLE  = ROOT / "firmware" / "secrets.example.h"

def generate():
    key_bytes = secrets.token_bytes(16)
    hex_vals  = ", ".join(f"0x{b:02X}" for b in key_bytes)
    formatted = ", ".join(f"0x{b:02X}" for b in key_bytes)

    content = textwrap.dedent(f"""\
        /**
         * secrets.h  — AUTO-GENERATED BY gen_key.py — DO NOT COMMIT
         * -----------------------------------------------------------
         * AES-128 pre-shared key for IRONCLAD LoRa encrypted link.
         * Flash BOTH ESP32s after regenerating this file.
         *
         * Regenerate any time you suspect key compromise:
         *     python scripts/gen_key.py
         */

        #pragma once

        // AES-128-GCM pre-shared key (16 bytes, generated {__import__('datetime').datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')})
        static const uint8_t IRONCLAD_PSK[16] = {{
            {formatted}
        }};
    """)

    OUT_FILE.write_text(content, encoding="utf-8")
    print(f"[OK]  Written: {OUT_FILE}")
    print(f"      Key hex: {key_bytes.hex()}")
    print()
    print("  NEXT STEPS:")
    print("  1. Flash  firmware/ironclad_tx  to the controller ESP32")
    print("  2. Flash  firmware/ironclad_rx  to the rover ESP32")
    print("  3. Never commit secrets.h  (already in .gitignore)")

if __name__ == "__main__":
    generate()
